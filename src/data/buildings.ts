export interface BuildingDef {
  readonly key: string;
  readonly name: string;
  readonly description: string;
  /** Lado de la huella en casillas. */
  readonly size: number;
  readonly cost: Cost;
  /** Segundos de construcción con un solo aldeano. */
  readonly buildTime: number;
  readonly hp: number;
  /** Población que aporta al terminarse. */
  readonly pop: number;
  /** Recursos que se pueden entregar aquí. */
  readonly dropsite: readonly Resource[];
  /** Unidades que entrena. */
  readonly trains: readonly UnitType[];
  /** Bloquea el paso (las granjas no). */
  readonly blocks: boolean;
  /** Edificio terminado que hace falta para poder construirlo. */
  readonly requires?: BuildingType;
  /** Comida de una granja. */
  readonly food?: number;
  readonly armor: DamagePair;
  /** Radio de visión en casillas, desde el borde de la huella. */
  readonly los: number;
  /** Dispara flechas (centro de la villa, torres): una por defecto y una más por unidad guarecida. */
  readonly attack?: AttackDef;
  /** Unidades que caben dentro. */
  readonly garrison?: number;
  /** Era mínima para construirlo (0 = Señorío). */
  readonly era?: number;
  /** Cuenta como edificio de su era para poder avanzar a la siguiente. */
  readonly countsForEra?: boolean;
  /** Muro (empalizada, muralla, puerta): no cuenta para la conquista. */
  readonly wall?: boolean;
  /** Puerta: sus dueños pasan, los demás no. */
  readonly gate?: boolean;
  /** Maravilla: si aguanta en pie el tiempo indicado, su dueño gana. */
  readonly wonder?: boolean;
}

