export interface UnitDef {
  /** Identificador estable en los datos. */
  readonly key: string;
  /** Nombre visible. */
  readonly name: string;
  readonly description: string;
  /** Velocidad en casillas por segundo. */
  readonly speed: number;
  /** Radio de colisión en casillas. */
  readonly radius: number;
  readonly hp: number;
  readonly cost: Cost;
  /** Segundos de entrenamiento. */
  readonly trainTime: number;
  /** Población que ocupa (0 = no cuenta, como los animales). */
  readonly pop: number;
  readonly classes: readonly UnitClass[];
  readonly armor: DamagePair;
  readonly attack?: AttackDef;
  /** Radio de visión en casillas. */
  readonly los: number;
  readonly stance: Stance;
  /** Puede recolectar y construir. */
  readonly worker?: boolean;
  /** Carga máxima de recursos. */
  readonly carry?: number;
  /** Comida que deja al morir (animales). */
  readonly food?: number;
  /** Huye cuando le atacan (ciervos). */
  readonly flees?: boolean;
  /** Ataca a cualquiera que vea aunque sea de la naturaleza (lobos). */
  readonly hostile?: boolean;
  /** Era mínima para entrenarla (0 = Señorío). */
  readonly era?: number;
  /** Solo puede atacar edificios (ariete). */
  readonly buildingsOnly?: boolean;
  /** Segundos para montarse o desmontarse; solo dispara montada y solo anda desmontada (trabuquete). */
  readonly deployTime?: number;
  /** Cura y convierte (monje). */
  readonly monk?: boolean;
  /** Comercia entre mercados (carro de comercio). */
  readonly trader?: boolean;
  /** Unidad única de una facción (se entrena en el castillo). */
  readonly faction?: number;
  /** Edificio terminado que hace falta para entrenarla (tipo de edificio). */
  readonly requires?: number;
}

